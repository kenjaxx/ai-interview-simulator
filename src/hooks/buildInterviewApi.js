import { MAX_FOLLOW_UPS } from "../lib/interviewConfig"

// Shapes everything useInterview knows into the three objects the screens use. Pure: no state,
// no effects. `c` is the bag of values and handlers passed in by useInterview.
export function buildInterviewApi(c) {
  const { form, speech, controls } = c

  return {
    screen: c.screen,
    setScreen: c.setScreen,

    setup: {
      role: form.role,
      setRole: form.setRole,
      customRole: form.customRole,
      setCustomRole: form.setCustomRole,
      effectiveRole: form.effectiveRole,
      roleReady: form.roleReady,
      seniority: form.seniority,
      setSeniority: form.setSeniority,
      questionCount: form.questionCount,
      setQuestionCount: form.setQuestionCount,
      questionType: form.questionType,
      setQuestionType: form.setQuestionType,
      aiMode: c.effectiveMode,
      setAiMode: form.setAiMode,
      quota: c.quota,
      quotaStatus: c.quotaStatus,
      quotaExhausted: c.quotaExhausted,
      refreshQuota: c.refreshQuota,
      jobDescription: form.jobDescription,
      setJobDescription: form.setJobDescription,
      jdAvailable: c.jdAvailable,
      followUps: form.followUps,
      setFollowUps: form.setFollowUps,
      followUpsAvailable: c.followUpsAvailable,
      saveHistory: form.saveHistory,
      setSaveHistory: form.setSaveHistory,
      speechLang: form.speechLang,
      selectAccent: form.selectAccent,
      ttsVoiceURI: form.ttsVoiceURI,
      setTtsVoiceURI: form.setTtsVoiceURI,
      ttsRate: form.ttsRate,
      setTtsRate: form.setTtsRate,
      voices: speech.voices,
      previewAccent: speech.previewAccent,
      previewVoice: speech.previewVoice,
      stopPreview: speech.stopPreview,
      starting: c.starting,
      setupMode: c.setupMode,
      setInputPref: form.setInputPref,
      support: speech.support,
      mic: speech.mic,
      notice: c.notice,
      maxFollowUps: MAX_FOLLOW_UPS,
      start: c.startInterview,
      draft: c.draftSummary,
      resumeDraft: c.resumeInterview,
      discardDraft: c.discardDraft,
    },

    interview: {
      orbState: c.orbState,
      currentQuestion: c.currentQuestion,
      questionIndex: c.questionIndex,
      questionTotal: c.questionTotal,
      answeredCount: c.answeredCount,
      inputMode: c.inputMode,
      error: c.error,
      awaitingFinalScore: c.awaitingFinalScore,
      sessionMode: c.sessionMode,
      sessionNote: c.sessionNote,
      isFollowUp: c.isFollowUp,
      preparingFollowUp: c.preparingFollowUp,
      skipFollowUp: controls.skipFollowUp,
      isRetry: c.retryIndex !== null,
      retryQuestionNumber: c.retryIndex !== null ? c.retryIndex + 1 : null,
      voiceOk: speech.voiceOk,
      ttsSupported: speech.ttsSupported,
      isListening: speech.isListening,
      getLevel: speech.getLevel,
      subscribeWord: speech.subscribeWord,
      subscribeTranscript: speech.subscribeTranscript,
      getTranscript: speech.getTranscript,
      finishAnswer: speech.finishAnswer,
      reviewDraft: c.reviewDraft,
      submitReview: controls.submitReview,
      submitTyped: controls.submitTyped,
      retry: controls.retry,
      replay: controls.replay,
      reRecord: controls.reRecord,
      skip: controls.skip,
      endEarly: controls.endEarly,
      cancelRetry: c.cancelRetry,
      switchToText: controls.switchToText,
      switchToVoice: controls.switchToVoice,
      scoreWithPractice: controls.scoreWithPractice,
    },

    summary: {
      uid: c.uid,
      session: c.session,
      meta: c.sessionMeta,
      overallSummary: c.overallSummary,
      sessionMode: c.sessionMode,
      usage: c.usage,
      saveStatus: c.saveStatus,
      retrySave: c.retrySave,
      restart: c.restart,
      retryResults: c.retryResults,
      weakestIndex: c.weakestIndex,
      startRetry: c.startRetry,
      retryUsesAi: c.sessionMode === "full" && !c.quotaExhausted,
    },
  }
}